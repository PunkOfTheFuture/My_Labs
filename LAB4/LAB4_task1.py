# TODO: описать базовый класс
class game:

    name = None      # Название (str)
    genre = None     # Жанр (str)
    rating = None    # Рейтинг (int)


    def __init__(self, name, genre, rating):   # Создание объекта класса game

        if not isinstance(name, str):
            raise TypeError("Имя указано неверно")   # При введении названия, которое не является строкой, выдаётся ошибка типа

        self.name = name   # При отсутствии ошибок введённое значение записывается в поле класса


        if not isinstance(genre, str):
            raise TypeError("Жанр указан неверно")   # При введении жанра, который не является строкой, выдаётся ошибка типа

        self.genre = genre    # При отсутствии ошибок введённое значение записывается в поле класса


        if not isinstance(rating, int):
            raise TypeError("Рейтинг указан неправильно")    # При введении рейтинга, который не является целочисленным, выдаётся ошибка типа
        if rating < 0:
            raise ValueError("Рейтинг не может быть ниже 0")    # Если значение рейтинга меньше 0, выдаётся ошибка значения
        if rating > 100:
            raise ValueError("Рейтинг не может быть выше 100")    # Если значение рейтинга выше 100, выдаётся ошибка значения

        self.rating = rating    # При отсутствии ошибок введённое значение записывается в поле класса


    def __str__(self):    # Магический метод __str__
        print(f"Название: {self.name}, Жанр: {self.genre}, Рейтинг: {self.rating}")    # Метод выводит в консоль полную информацию об объекте


    def __repr__(self):    # Магический метод __repr__
        return f"game({self.name!r}, {self.genre!r}, {self.rating!r}"    # Метод возвращает строку валидного кода создания данного объекта класса



