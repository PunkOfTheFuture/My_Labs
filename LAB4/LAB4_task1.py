class Dota2(game):

    anop = 500000    # average number of players

    def __init__(self, name = None, genre = None, rating = None, anop = 0):    # Создание объекта класса Dota2
        super().__init__(name, genre, rating)

        if not isinstance(anop, int):
            raise TypeError("Среднее количество игроков указано неверно")    # При введении среднего числа игроков, которое не является целочисленным, выдаётся ошибка типа

        if anop < 0:
            raise ValueError("Среднее количество игроков не может быть меньше 0")    # Если значение среднего числа игроков меньше 0, выдаётся ошибка значения

        self.anop = anop    # При отсутствии ошибок введённое значение записывается в поле класса



    def __str__(self):    # Магический метод __str__
        print(super.__str__() + f", Среднее количество игроков: {self.anop}")    # Метод выводит в консоль полную информацию об объекте


    def __repr__(self):    # Магический метод __repr__
        return super.__repr__() + f", {self.anop!r}"    # Метод возвращает строку валидного кода создания данного объекта класса











